#!/usr/bin/env node
// Generates the CSS for the design tokens from design/tokens.json:
//   src/styles/tokens.css  custom properties (--cn-*), light + dark themes
//   src/styles/theme.css   Tailwind v4 @theme mapping onto those properties
// tokens.json is the only place values live. Run after every token change.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const t = JSON.parse(readFileSync('design/tokens.json', 'utf8'));
const px = (n) => `${n / 16}rem`;
const header = '/* Generated by scripts/tokens.mjs from design/tokens.json. Do not edit. */\n';

const colorVars = (set) =>
  Object.entries(set).map(([k, v]) => `  --cn-${k}: ${v};`).join('\n');

const tokensCss = `${header}
:root {
${colorVars(t.color.light)}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${colorVars(t.color.dark).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${colorVars(t.color.dark)}
  color-scheme: dark;
}

:root {
  --cn-font-sans: ${t.font.sans};
  --cn-font-mono: ${t.font.mono};
${Object.entries(t.radius).map(([k, v]) => `  --cn-radius-${k}: ${v === 999 ? '999px' : px(v)};`).join('\n')}
${Object.entries(t.shadow).map(([k, v]) => `  --cn-shadow-${k}: ${v};`).join('\n')}
  --cn-motion-fast: ${t.motion.fast};
  --cn-motion-base: ${t.motion.base};
  --cn-motion-slow: ${t.motion.slow};
  --cn-ease: ${t.motion.ease};
${Object.entries(t.layout).map(([k, v]) => `  --cn-${k}: ${px(v)};`).join('\n')}
}
`;

// Tailwind class names: the role names, except text colours, which become
// text-fg / text-muted so you never write text-text.
const twColorName = { text: 'fg', 'text-muted': 'muted' };
const colorTheme = Object.keys(t.color.light)
  .map((k) => `  --color-${twColorName[k] ?? k}: var(--cn-${k});`)
  .join('\n');

const typeTheme = Object.entries(t.type)
  .map(([k, v]) => `  --text-${k}: ${px(v.size)};\n  --text-${k}--line-height: ${px(v.line)};\n  --text-${k}--font-weight: ${v.weight};`)
  .join('\n');

const themeCss = `${header}
@theme inline {
  --color-*: initial;
${colorTheme}
  --color-transparent: transparent;
  --color-current: currentColor;

  --font-sans: var(--cn-font-sans);
  --font-mono: var(--cn-font-mono);

  --text-*: initial;
${typeTheme}

  --spacing: ${px(t.space[1])};

  --radius-*: initial;
${Object.keys(t.radius).map((k) => `  --radius-${k}: var(--cn-radius-${k});`).join('\n')}

  --shadow-*: initial;
${Object.keys(t.shadow).map((k) => `  --shadow-${k}: var(--cn-shadow-${k});`).join('\n')}

  --ease-out: var(--cn-ease);
  --breakpoint-md: ${px(t.layout['breakpoint-md'])};
  --breakpoint-lg: ${px(t.layout['breakpoint-lg'])};
}
`;

mkdirSync('src/styles', { recursive: true });
writeFileSync('src/styles/tokens.css', tokensCss);
writeFileSync('src/styles/theme.css', themeCss);
console.log('wrote src/styles/tokens.css and src/styles/theme.css');
